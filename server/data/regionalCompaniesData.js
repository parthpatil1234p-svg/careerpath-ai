function getCompaniesByProximity(city = null, maxDistanceKm = null) {
  let list = [...regionalCompanies];
  if (city && city.toLowerCase() !== 'all') {
    const cLower = city.toLowerCase();
    list = list.filter(item => item.city && item.city.toLowerCase().includes(cLower));
  }
  if (maxDistanceKm && !isNaN(maxDistanceKm)) {
    const max = Number(maxDistanceKm);
    list = list.filter(item => item.distanceKm <= max);
  }
  return list.sort((a, b) => a.distanceKm - b.distanceKm);
}

